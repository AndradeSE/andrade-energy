import { createHash, randomUUID } from 'node:crypto';
import { Client } from 'pg';
import { neonProductionConnection } from './neonSnapshotRuntime';
import { sourceSupabase } from './supabase';
import { EMPRESA_ANDRADE_ID } from './empresa';

const initializeSql=`
CREATE TABLE IF NOT EXISTS reserve_control.recovery_instance (
 instance_key text PRIMARY KEY, provider text NOT NULL CHECK(provider IN ('SUPABASE','NEON')));
CREATE TABLE IF NOT EXISTS reserve_control.recovery_notice (
 id uuid PRIMARY KEY, instance_key text NOT NULL, usuario_id uuid NOT NULL, empresa_id uuid NOT NULL,
 provider text NOT NULL CHECK(provider IN ('SUPABASE','NEON')), created_at timestamptz NOT NULL DEFAULT now(),
 push_attempted boolean NOT NULL DEFAULT false, source_saved boolean NOT NULL DEFAULT false);
ALTER TABLE reserve_control.recovery_instance ENABLE ROW LEVEL SECURITY;
ALTER TABLE reserve_control.recovery_notice ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON reserve_control.recovery_instance,reserve_control.recovery_notice FROM PUBLIC,anonymous,authenticated;`;

export async function prepareRecoveryEvents(env: NodeJS.ProcessEnv) {
 const pg=new Client(neonProductionConnection(env));
 try { await pg.connect();await pg.query('BEGIN');await pg.query(initializeSql);await pg.query('COMMIT'); }
 catch(error) {await pg.query('ROLLBACK').catch(()=>{});throw error;} finally {await pg.end();}
}

export function recoveryNotice(provider: 'SUPABASE'|'NEON') {
 return provider==='NEON'
  ? {tipo:'BANCO_RESERVA_ATIVADO',titulo:'Banco reserva em consulta',detalhe:'Esta instância está usando a cópia Neon. Alterações, cobranças e protocolos estão bloqueados até o retorno do banco principal.'}
  : {tipo:'BANCO_PRINCIPAL_RESTAURADO',titulo:'Consulta voltou ao banco principal',detalhe:'Esta instância voltou a usar o Supabase. Confira o estado das tarefas no aplicativo.'};
}

/** Private outbox survives source failure. No event is generated by the snapshot collector. */
export async function publishRecoveryTransition(env: NodeJS.ProcessEnv,provider:'SUPABASE'|'NEON',options={deliver:true}) {
 const pg=new Client(neonProductionConnection(env));
 const instance=createHash('sha256').update(env.RENDER_SERVICE_ID || 'production-recovery').digest('hex');
 try {
  await pg.connect();await pg.query('BEGIN');
  await pg.query('SELECT pg_advisory_xact_lock(7071191)');
  const {rows:[previous]}=await pg.query('SELECT provider FROM reserve_control.recovery_instance WHERE instance_key=$1',[instance]);
  if(previous?.provider!==provider) {
   await pg.query(`INSERT INTO reserve_control.recovery_instance(instance_key,provider) VALUES($1,$2)
    ON CONFLICT(instance_key) DO UPDATE SET provider=excluded.provider`,[instance,provider]);
   if(previous || provider==='NEON') {
    const {rows:admins}=await pg.query(`SELECT DISTINCT u.id FROM public.usuarios u JOIN public.empresa_usuarios e ON e.usuario_id=u.id
     WHERE u.ativo=true AND u.perfil='ADMIN' AND u.empresa_id=$1 AND e.empresa_id=$1 AND e.ativo=true
     AND e.papel IN ('SUPERADMIN','ADMIN_EMPRESA')`,[EMPRESA_ANDRADE_ID]);
    for(const admin of admins) await pg.query(`INSERT INTO reserve_control.recovery_notice(id,instance_key,usuario_id,empresa_id,provider)
     VALUES($1,$2,$3,$4,$5)`,[randomUUID(),instance,admin.id,EMPRESA_ANDRADE_ID,provider]);
   }
  }
  await pg.query('COMMIT');
  if(!options.deliver) return;
  const {rows:notices}=await pg.query(`SELECT * FROM reserve_control.recovery_notice WHERE instance_key=$1
   AND (NOT push_attempted OR NOT source_saved) ORDER BY created_at LIMIT 20`,[instance]);
  for(const row of notices) {
   const text=recoveryNotice(row.provider);
   // Saving by deterministic ID and dedupe key allows retry after an uncertain source response.
   if(!row.source_saved) {
    const result=await sourceSupabase.from('notificacoes_app').insert({id:row.id,usuario_id:row.usuario_id,
     empresa_id:row.empresa_id,...text,rota:'/cotas-servicos',chave_dedupe:`neon-recovery:${row.id}`})
     .abortSignal(AbortSignal.timeout(3000));
    if(!result.error || result.error.code==='23505') await pg.query('UPDATE reserve_control.recovery_notice SET source_saved=true WHERE id=$1',[row.id]);
   }
   if(!row.push_attempted) {
    const {rows:devices}=await pg.query(`SELECT DISTINCT d.token FROM public.dispositivos_push d
     JOIN public.usuarios u ON u.id=d.usuario_id JOIN public.empresa_usuarios e ON e.usuario_id=u.id AND e.empresa_id=d.empresa_id
     WHERE d.usuario_id=$1 AND d.empresa_id=$2 AND d.ativo=true AND d.app_variante='gerador'
     AND u.ativo=true AND u.perfil='ADMIN' AND u.empresa_id=$2 AND e.ativo=true AND e.papel IN ('SUPERADMIN','ADMIN_EMPRESA')`,[row.usuario_id,row.empresa_id]);
    const tokens=devices.map(item=>String(item.token)).filter(token=>/^(ExponentPushToken|ExpoPushToken)\[[^\]]+\]$/.test(token));
    if(!tokens.length) continue;
    // Reserve the attempt before sending: an uncertain provider response must not repeat on every restart.
    const claim=await pg.query('UPDATE reserve_control.recovery_notice SET push_attempted=true WHERE id=$1 AND NOT push_attempted RETURNING id',[row.id]);
    if(!claim.rowCount) continue;
    for(let offset=0;offset<tokens.length;offset+=100) {
     const response=await fetch('https://exp.host/--/api/v2/push/send',{method:'POST',headers:{'Content-Type':'application/json',Accept:'application/json'},
      body:JSON.stringify(tokens.slice(offset,offset+100).map(to=>({to,title:text.titulo,body:'Abra Cotas de serviços para conferir o banco ativo.',
       sound:'default',channelId:'avisos-contexto',data:{notificacaoId:row.id,tipo:text.tipo,url:'/cotas-servicos'}}))),signal:AbortSignal.timeout(10_000)});
     if(!response.ok) console.warn('Aviso de recuperação permanece no histórico; push não confirmado.');
    }
   }
  }
 } catch(error) {await pg.query('ROLLBACK').catch(()=>{});throw error;}
 finally {await pg.end();}
}

export async function listPrivateRecoveryNotices(env:NodeJS.ProcessEnv,userId:string,empresaId:string) {
 const pg=new Client(neonProductionConnection(env));
 try {
  await pg.connect();
  const {rows}=await pg.query(`SELECT n.id,n.provider,n.created_at FROM reserve_control.recovery_notice n
   JOIN public.usuarios u ON u.id=n.usuario_id
   WHERE n.usuario_id=$1 AND n.empresa_id=$2 AND u.ativo=true AND u.perfil='ADMIN' AND u.empresa_id=$2
   ORDER BY n.created_at DESC LIMIT 30`,[userId,empresaId]);
  return rows.map(row=>({id:row.id,...recoveryNotice(row.provider),criado_em:row.created_at,rota:'/cotas-servicos'}));
 } finally {await pg.end();}
}
