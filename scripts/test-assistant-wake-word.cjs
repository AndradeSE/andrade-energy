const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const exportsForTest = {};
const code = ts.transpileModule(fs.readFileSync("services/assistant-wake-word.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
vm.runInNewContext(code, { exports: exportsForTest });
const { containsAssistantWakeWord, wakeWordEnabled, setWakeWordEnabled, subscribeWakeWord, wakeWordPaused, setWakeWordPaused } = exportsForTest;
for (const phrase of ["Andrade", " andrade ", "ANDRADE!", "“Andrade”"]) assert.equal(containsAssistantWakeWord(phrase), true, phrase);
for (const phrase of ["E aí, chat", "Andrade Energy", "Olá Andrade", "Andrade, pode me ajudar?", "andrad", "andradense", "chat", "boa noite"]) assert.equal(containsAssistantWakeWord(phrase), false, phrase);
assert.equal(wakeWordEnabled(), false);
let notifications = 0;
const unsubscribe = subscribeWakeWord(() => notifications++);
setWakeWordEnabled(true);
assert.equal(wakeWordEnabled(), true);
assert.equal(notifications, 1);
unsubscribe();
setWakeWordEnabled(false);
exportsForTest.setWakeWordReady(true);
assert.equal(exportsForTest.wakeWordReady(), true);
setWakeWordEnabled(false);
assert.equal(exportsForTest.wakeWordReady(), false);
assert.equal(notifications, 1);
setWakeWordPaused(true);
assert.equal(wakeWordPaused(), true);
setWakeWordPaused(false);
assert.equal(wakeWordPaused(), false);
setWakeWordEnabled(true, false, true);
assert.equal(exportsForTest.wakeWordRemainingMs(), Infinity, "Escuta local autorizada não deve expirar em 60 segundos");
assert.equal(exportsForTest.wakeWordOnlineConsent(), false, "Escuta local não pode enviar áudio ambiente à nuvem");
setWakeWordEnabled(false);
console.log("PASS: frase de ativação, falsos positivos, escuta desligada por padrão e controle de sessão");
const component = fs.readFileSync("components/assistant/AssistantWakeWord.tsx", "utf8");
assert.doesNotMatch(component, /if \(!enabled \|\| !foreground \|\| paused \|\| loading \|\| pathname/, "Chat ocioso não deve bloquear a captura nem o prazo de inicialização");
assert.match(component, /!foreground \|\| paused \|\| loading/);
assert.match(component, /startupDeadline = setTimeout/);
assert.match(component, /automaticLocalWakeConsent\(userId\)/, "Preferência local deve voltar ao abrir o app");
assert.match(component, /isVoiceInstalled\(\)/, "Não iniciar escuta local sem modelo instalado");
assert.match(component, /if \(cancelled \|\| triggered\) return;/, "Encerramento após reconhecer a frase não pode tratar o stop como falha");
assert.match(component, /AppState\.currentState !== "active" \|\| !wakeWordEnabled\(\)/, "Handoff não deve depender da montagem da escuta antiga");
assert.match(fs.readFileSync("services/on-device-voice.ts", "utf8"), /promptPreviousSlices: false/, "Resultados anteriores não podem contaminar a frase de ativação seguinte");
const floating = fs.readFileSync("components/assistant/FloatingAssistant.tsx", "utf8");
assert.match(floating, /router\.push\("\/assistente"\)/, "Toque no botão flutuante deve apenas abrir a Ajuda");
assert.doesNotMatch(floating, /setWakeWordEnabled\(false\)/, "Abrir a Ajuda não pode desligar a escuta opcional");
assert.match(floating, /embeddedVoiceWake=\{conversationRequest\}/, "A conversa iniciada por voz deve aparecer sobre a tela atual");
const helpScreen = fs.readFileSync("app/assistente.tsx", "utf8");
assert.match(helpScreen, /toggleVoice\(true\)/, "Ativação pelo comando falado deve iniciar a escuta");
assert.doesNotMatch(helpScreen, /configureWakeWord|Ativar escuta automática local/, "A Ajuda não deve repetir o controle de ativação da conversa");
assert.match(helpScreen, /}, 5_000\)/, "A conversa aberta pelo comando deve encerrar após cinco segundos sem fala");
const profile = fs.readFileSync("app/(tabs)/perfil.tsx", "utf8");
assert.match(profile, /Comando de voz “Andrade”/, "O consentimento da escuta deve ficar no Perfil, fora da Ajuda");
assert.match(helpScreen, /stopNativePortugueseSpeech\(\)\.finally\(\(\) => setWakeWordPaused\(false\)\)/, "Ao voltar, solte o microfone antes de retomar o comando");
assert.match(helpScreen, /if \(!wakeWordEnabled\(\)\) void releaseVoiceRecognition\(\)/, "Sair da Ajuda não pode liberar a escuta global ativa na Home");
assert.match(fs.readFileSync("services/on-device-voice.ts", "utf8"), /export async function releaseVoiceRecognition\(\) \{\s*await stopContinuousListening\(\)/, "Liberar o reconhecedor também encerra a escuta global");
