const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const exportsForTest = {};
const code = ts.transpileModule(fs.readFileSync("services/assistant-wake-word.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
vm.runInNewContext(code, { exports: exportsForTest });
const { containsAssistantWakeWord, wakeWordEnabled, setWakeWordEnabled, subscribeWakeWord, wakeWordPaused, setWakeWordPaused } = exportsForTest;
for (const phrase of ["E aí, chat!", "e ai chat", "e aii chat", "E aí chate", "e aí chat como vai?"]) assert.equal(containsAssistantWakeWord(phrase), true);
for (const phrase of ["chat", "e aí", "esse chat", "abri o chat", "e aí chato"]) assert.equal(containsAssistantWakeWord(phrase), false);
assert.equal(wakeWordEnabled(), false);
let notifications = 0;
const unsubscribe = subscribeWakeWord(() => notifications++);
setWakeWordEnabled(true);
assert.equal(wakeWordEnabled(), true);
assert.equal(notifications, 1);
unsubscribe();
setWakeWordEnabled(false);
assert.equal(notifications, 1);
setWakeWordPaused(true);
assert.equal(wakeWordPaused(), true);
setWakeWordPaused(false);
assert.equal(wakeWordPaused(), false);
console.log("PASS: frase de ativação, falsos positivos, escuta desligada por padrão e controle de sessão");
