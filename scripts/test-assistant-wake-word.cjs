const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const exportsForTest = {};
const code = ts.transpileModule(fs.readFileSync("services/assistant-wake-word.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
vm.runInNewContext(code, { exports: exportsForTest });
const { containsAssistantWakeWord, wakeWordEnabled, setWakeWordEnabled, subscribeWakeWord, wakeWordPaused, setWakeWordPaused } = exportsForTest;
for (const phrase of ["Andrade", " andrade ", "ANDRADE!", "“Andrade”"]) assert.equal(containsAssistantWakeWord(phrase), true, phrase);
for (const phrase of ["E aí, chat", "Andrade Energy", "Olá Andrade", "Andrade, pode me ajudar?", "andrad", "andradense", "chat", "boa noite"]) assert.equal(containsAssistantWakeWord(phrase), false, phrase);
assert.equal(wakeWordEnabled(), false);
let notifications = 0;
const unsubscribe = subscribeWakeWord(() => notifications++);
setWakeWordEnabled(true);
assert.equal(wakeWordEnabled(), true);
assert.equal(notifications, 1);
unsubscribe();
setWakeWordEnabled(false);
exportsForTest.setWakeWordReady(true);
assert.equal(exportsForTest.wakeWordReady(), true);
setWakeWordEnabled(false);
assert.equal(exportsForTest.wakeWordReady(), false);
assert.equal(notifications, 1);
setWakeWordPaused(true);
assert.equal(wakeWordPaused(), true);
setWakeWordPaused(false);
assert.equal(wakeWordPaused(), false);
console.log("PASS: frase de ativação, falsos positivos, escuta desligada por padrão e controle de sessão");
const component = fs.readFileSync("components/assistant/AssistantWakeWord.tsx", "utf8");
assert.equal(component.includes('pathname === "/assistente"'), false, "Chat ocioso não deve bloquear a captura nem o prazo de inicialização");
assert.match(component, /!foreground \|\| paused \|\| loading/);
assert.match(component, /startupDeadline = setTimeout/);
assert.match(fs.readFileSync("services/on-device-voice.ts", "utf8"), /promptPreviousSlices: false/, "Resultados anteriores não podem contaminar a frase de ativação seguinte");
const floating = fs.readFileSync("components/assistant/FloatingAssistant.tsx", "utf8");
assert.match(floating, /router\.push\(\{ pathname: "\/assistente", params: \{ voiceWake:/, "Toque no botão flutuante deve iniciar a conversa");
const helpScreen = fs.readFileSync("app/assistente.tsx", "utf8");
assert.match(helpScreen, /toggleVoice\(voiceGreeting !== "1"\)/, "Comando falado deve escutar sem saudação; o botão flutuante pode saudar");
