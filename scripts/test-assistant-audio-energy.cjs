const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const exportsForTest = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('services/assistant-audio-energy.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exportsForTest, DataView });
const check = exportsForTest.hasAssistantVoiceEnergy;
const voiceSource = fs.readFileSync('services/on-device-voice.ts', 'utf8');
assert.equal(voiceSource.includes('assistantPcm16ToFloat32'), false, 'O stream PCM16 deve chegar intacto à API nativa');
assert.match(voiceSource, /whisperContext: whisper/);
assert.equal(check(new Uint8Array()), false);
assert.equal(check(new Uint8Array(32000)), false);
const bytes = new Uint8Array(32000);
const pcm = new DataView(bytes.buffer);
for (let i = 0; i < 16000; i++) pcm.setInt16(i * 2, Math.round(Math.sin(i / 10) * 1800), true);
assert.equal(check(bytes), true);
assert.equal(check(bytes.subarray(2)), true);
console.log('PASS: silêncio rejeitado e PCM16 com energia aceito, inclusive subarray');
const known = new ArrayBuffer(8);
const knownPcm = new DataView(known);
[0, 32767, -32768, 16384].forEach((value, index) => knownPcm.setInt16(index * 2, value, true));
const converted = new Float32Array(exportsForTest.assistantPcm16ToFloat32(known));
assert.deepEqual(Array.from(converted), [0, 32767 / 32768, -1, 0.5]);
assert.equal(converted.byteLength, 16);
console.log('PASS: PCM16 convertido para Float32 normalizado sem reinterpretar bytes');
